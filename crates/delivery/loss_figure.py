#!/usr/bin/env python3
"""Draw figure 2: where the loss from moving lands, by hub role.

    python3 crates/delivery/loss_figure.py > paper/manuscript/figures/loss-by-hub.tex

Read the fixed-policy and model sweep results for 16 and 64 hubs. For each
day, split hubs by their part in the intervention: gave aircraft or stock,
only received, or neither. Show additional late or undelivered requests
per hundred of each group's requests relative to local rules on that day.
The model bars use the three Claude CLI arms; Luna's API run has no saved
per-hub results, so mixing its original CLI runs into this figure would
compare different client paths. Print the pooled numbers to stderr.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

GROUPS = ("gave", "received", "rest")
CONDITIONS = (("move", "move policy"), ("X", "models giving orders"),
              ("veto", "models as a veto"))
SIZES = ("hubs16", "hubs64")


ROOT = Path(__file__).resolve().parents[2]
MANAGER = "entities.region.autonomy.Dispatcher.manager."
SWEEPS = {
    "hubs16": ("region-16-fixed", "region-16-models"),
    "hubs64": ("region-64-fixed", "region-64-models"),
}


def rows(sweep):
    path = ROOT / "sweeps" / sweep / "run000" / "results.jsonl"
    return [json.loads(line) for line in path.read_text().splitlines()]


def results():
    found = {}
    for size, (fixed_sweep, model_sweep) in SWEEPS.items():
        for row in rows(fixed_sweep) + rows(model_sweep):
            if row["error"] is not None:
                raise ValueError(f"failed sweep case: {row['case_id']}")
            config = row["parameters"]
            kind = config[MANAGER + "kind"]
            policy = config.get(MANAGER + "policy", "")
            model = config.get(MANAGER + "model", "")
            if kind == "policy" and policy.endswith("/local.yaml"):
                arm = "local"
            elif kind == "policy" and policy.endswith("/move.yaml"):
                arm = "move"
            elif kind in ("model", "veto") and model.startswith("claude-"):
                arm = model + "-" + ("X" if kind == "model" else "veto")
            else:
                continue
            found[(size, row["seed"], arm)] = row["metrics"]["metrics/DeliveryScore:0"]["1"]
    return found


def lost(day, hub):
    return day.get(f"hub_{hub:03}_late", 0) + day.get(f"hub_{hub:03}_undelivered", 0)


MODELS = ("claude-haiku-5-5", "claude-sonnet-5-5", "claude-opus-5-5")


def condition_of(arm):
    """The move policy or a Claude model acting live or as a veto."""
    if arm == "move":
        return "move"
    model, _, role = arm.rpartition("-")
    if model in MODELS and role in ("X", "veto"):
        return role
    return None


def tally(runs):
    """(size, condition) -> group -> [extra lost, requests, days]."""
    totals = defaultdict(lambda: {g: [0.0, 0.0] for g in GROUPS})
    days = defaultdict(int)
    for (size, seed, arm), day in sorted(runs.items()):
        condition = condition_of(arm)
        local = runs.get((size, seed, "local"))
        if condition is None or local is None:
            continue
        hubs = range(1, int(size[4:]) + 1)
        gave = {h for h in hubs if day.get(f"hub_{h:03}_gave", 0) > 0}
        received = {h for h in hubs if day.get(f"hub_{h:03}_got", 0) > 0} - gave
        rest = set(hubs) - gave - received
        for group, members in zip(GROUPS, (gave, received, rest)):
            cell = totals[(size, condition)][group]
            cell[0] += sum(lost(day, h) - lost(local, h) for h in members)
            cell[1] += sum(local.get(f"hub_{h:03}_requests", 0) for h in members)
        days[(size, condition)] += 1
    return totals, days


def per_hundred(totals):
    return {key: {g: 100.0 * v[0] / v[1] if v[1] else 0.0 for g, v in cells.items()}
            for key, cells in totals.items()}


def draw(rates, days):
    """TikZ for a column-width chart: two size panels of three conditions."""
    width_cm, bar_cm, gap_cm = 8.6, 0.28, 0.07
    cluster_cm = 3 * bar_cm + 2 * gap_cm
    y_per_point, y_top, y_bottom = 0.16, 20.0, -5.0
    colors = {"gave": "orange", "received": "black!45", "rest": "black!20"}
    out = ["% Generated by crates/delivery/loss_figure.py; do not edit by hand.",
           f"\\begin{{tikzpicture}}[x=1cm, y=1cm, font=\\scriptsize]"]
    x_axis = 1.0

    def y(value):
        return 3.3 + value * y_per_point  # 3.3 cm up is the zero line

    # Grid and axis.
    for tick in (-5, 0, 5, 10, 15, 20):
        shade = "black!35" if tick == 0 else "black!10"
        out.append(f"\\draw[{shade}, line width=0.4pt] ({x_axis},{y(tick):.2f}) -- ({width_cm},{y(tick):.2f});")
        out.append(f"\\node[anchor=east, text=muted, inner sep=2pt] at ({x_axis},{y(tick):.2f}) {{{tick:+d}}};".replace("{+0}", "{0}"))
    out.append(f"\\node[anchor=south, rotate=90, text=muted] at (0.25,{y(7.5):.2f}) "
               "{more requests lost per 100, vs local rules};")
    x = x_axis + 0.35
    for size in SIZES:
        panel_start = x
        for condition, label in CONDITIONS:
            key = (size, condition)
            for group in GROUPS:
                value = rates[key][group]
                top, bottom = (y(max(value, 0.0)), y(min(value, 0.0)))
                out.append(f"\\fill[{colors[group]}] ({x:.2f},{bottom:.2f}) rectangle ({x + bar_cm:.2f},{top:.2f});")
                anchor, place = ("south", top + 0.04) if value >= 0 else ("north", bottom - 0.04)
                out.append(f"\\node[anchor={anchor}, inner sep=0pt, font=\\tiny, text=black!70] "
                           f"at ({x + bar_cm / 2:.2f},{place:.2f}) {{{round(value) or 0}}};")
                x += bar_cm + gap_cm
            x -= gap_cm
            out.append(f"\\node[anchor=north, text width={cluster_cm + 0.3:.2f}cm, align=center, inner sep=1pt, "
                       f"font=\\tiny, text=black!70] at ({x - cluster_cm / 2:.2f},{y(y_bottom) - 0.08:.2f}) "
                       f"{{{label}, {days[key]} runs}};")
            x += 0.3
        x += 0.2
        label = f"{size[4:]} hubs"
        out.append(f"\\node[anchor=south, font=\\scriptsize\\bfseries] at ({(panel_start + x - 0.5) / 2:.2f},{y(y_top) + 0.05:.2f}) {{{label}}};")
    # Legend, one row under the title line.
    lx = x_axis + 0.35
    for group, text in (("gave", "hubs that gave aircraft or stock"),
                        ("received", "hubs that only received"), ("rest", "neither")):
        out.append(f"\\fill[{colors[group]}] ({lx:.2f},{y(y_top) + 0.72:.2f}) rectangle ({lx + 0.25:.2f},{y(y_top) + 0.9:.2f});")
        out.append(f"\\node[anchor=west, inner sep=2pt, text=black!70] at ({lx + 0.25:.2f},{y(y_top) + 0.81:.2f}) {{{text}}};")
        lx += 0.5 + 0.11 * len(text)
    out.append("\\end{tikzpicture}")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 1:
        sys.exit(__doc__)
    totals, days = tally(results())
    rates = per_hundred(totals)
    for key in sorted(rates):
        cells = totals[key]
        print(key, f"{days[key]} runs;", " ".join(
            f"{g}: {cells[g][0] / days[key]:+.1f}/day, {rates[key][g]:+.1f} per 100 of {cells[g][1] / days[key]:.0f}"
            for g in GROUPS), file=sys.stderr)
    sys.stdout.write(draw(rates, days))


if __name__ == "__main__":
    main()
