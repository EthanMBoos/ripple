#!/usr/bin/env python3
"""Draw the matched-day surge comparison for the paper.

    python3 crates/delivery/surge_figure.py \
        sweeps/region-surge-length/run001/results.jsonl \
        sweeps/region-surge-informed/run000/results.jsonl \
        sweeps/region-surge-informed-240/run000/results.jsonl \
        > paper/manuscript/figures/surge-informed.tex
"""

from __future__ import annotations

import math
import statistics
import sys

from surge_compare import read


LENGTHS = (15, 60, 120, 240)
ARMS = (
    ("return", "Return rule", "black", "square"),
    ("opus-5-5", "Opus", "orange", "circle"),
    ("haiku-5-5", "Haiku", "muted", "open"),
)
XS = (1.35, 3.00, 4.65, 6.30)


def marker(x, y, color, shape, small=False):
    radius = 0.035 if small else 0.065
    if shape == "square":
        return (f"\\fill[{color}] ({x-radius:.3f},{y-radius:.3f}) "
                f"rectangle ({x+radius:.3f},{y+radius:.3f});")
    if shape == "open" and not small:
        return (f"\\draw[{color}, fill=white, line width=0.7pt] "
                f"({x:.3f},{y:.3f}) circle ({radius:.3f});")
    return f"\\fill[{color}] ({x:.3f},{y:.3f}) circle ({radius:.3f});"


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    fixed = read(sys.argv[1])
    models = {}
    for path in sys.argv[2:]:
        for key, metrics in read(path).items():
            if key in models:
                raise ValueError(f"duplicate model day {key}")
            models[key] = metrics

    values = {}
    for length in LENGTHS:
        for arm, _, _, _ in ARMS:
            source = fixed if arm == "return" else models
            seeds = range(1, 6)
            if any((length, seed, arm) not in source for seed in seeds):
                raise ValueError(f"incomplete comparison for {length} min, {arm}")
            scores = [
                100 * (source[length, seed, arm]["score"]
                       - fixed[length, seed, "local"]["score"])
                for seed in seeds
            ]
            moves = [source[length, seed, arm].get("moves", 0) for seed in seeds]
            values[length, arm] = (scores, moves)

    score_days = [v for scores, _ in values.values() for v in scores]
    moves_days = [v for _, moves in values.values() for v in moves]
    score_low = min(-5, 5 * math.floor(min(score_days) / 5))
    score_high = max(10, 5 * math.ceil(max(score_days) / 5))
    moves_high = max(50, 25 * math.ceil(max(moves_days) / 25))
    y_score = lambda value: 3.25 + 2.10 * (value - score_low) / (score_high - score_low)
    y_moves = lambda value: 0.55 + 1.65 * value / moves_high

    out = [
        "% Generated by crates/delivery/surge_figure.py; do not edit by hand.",
        "\\begin{tikzpicture}[x=1cm,y=1cm,font=\\scriptsize]",
    ]
    for value in range(score_low, score_high + 1, 5):
        y = y_score(value)
        shade = "black!35" if value == 0 else "black!12"
        out.append(f"\\draw[{shade}] (1.1,{y:.3f}) -- (6.65,{y:.3f});")
        out.append(f"\\node[anchor=east, inner sep=1pt] at (1.03,{y:.3f}) {{{value:+d}}};")
    for value in range(0, moves_high + 1, 25):
        y = y_moves(value)
        out.append(f"\\draw[black!12] (1.1,{y:.3f}) -- (6.65,{y:.3f});")
        out.append(f"\\node[anchor=east, inner sep=1pt] at (1.03,{y:.3f}) {{{value}}};")
    out.extend([
        "\\node[rotate=90, anchor=south] at (0.05,4.3) "
        "{Score gain vs local rules (points)};",
        "\\node[rotate=90, anchor=south] at (0.05,1.4) "
        "{Move orders per day};",
    ])

    for arm, label, color, shape in ARMS:
        for panel, y_fn in ((0, y_score), (1, y_moves)):
            path = []
            for x, length in zip(XS, LENGTHS):
                days = values[length, arm][panel]
                mean = statistics.mean(days)
                lo, hi = min(days), max(days)
                out.append(
                    f"\\draw[{color}, line width=0.5pt] "
                    f"({x:.3f},{y_fn(lo):.3f}) -- ({x:.3f},{y_fn(hi):.3f});"
                )
                path.append((x, y_fn(mean)))
            segments = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in path)
            style = f"{color}, line width=1pt"
            if shape == "open":
                style += ", dashed"
            out.append(f"\\draw[{style}] {segments};")
            out.extend(marker(x, y, color, shape) for x, y in path)

    for x, length in zip(XS, LENGTHS):
        out.append(f"\\node[anchor=north] at ({x:.3f},0.42) {{{length}}};")
    out.append("\\node[anchor=north] at (3.85,0.08) {Surge length (min)};")
    for index, (_, label, color, shape) in enumerate(ARMS):
        x = 1.15 + index * 2.0
        out.append(f"\\draw[{color}, line width=1pt] ({x:.2f},5.72) -- ({x+0.35:.2f},5.72);")
        out.append(marker(x + 0.175, 5.72, color, shape))
        out.append(f"\\node[anchor=west, inner sep=2pt] at ({x+0.40:.2f},5.72) {{{label}}};")
    out.append("\\end{tikzpicture}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
