def generated_table():
    results = cases(GENERATED)
    if not results:
        return None
    frames = [result["comparison"] for result in results]
    traces = [result["trace_comparison"] for result in results]
    agreement = [result["summary_agreement"] for result in results]
    # (label, text that appears in a mission only when the feature is used)
    features = [("collisions", ">SimpleCollision<"), ("ground", ">GroundCollision<"),
                ("boundary", ">Boundary<"), ("scheduled spawns", "<generate_rate>"),
                ("NoisyState", ">NoisyState<"), ("NoisyContacts", ">NoisyContacts<"),
                ("fixed-wing", ">FixedWing6DOF<"), ("point-mass", ">SingleIntegrator<")]
    counts = []
    for label, marker in features:
        counts.append(sum(marker in (GENERATED / r["case"] / "input.xml").read_text()
                          for r in results))
    rows = [
        ("Scenarios passing", f"{sum(r['passed'] for r in results)} of {len(results)}"),
        ("Compared entity states", f"{sum(f['compared_entity_states'] for f in frames):,}"),
        ("Compared deliveries / outputs",
         f"{sum(t['deliveries'] for t in traces):,} / {sum(t['outputs'] for t in traces):,}"),
        ("Max position / velocity error",
         f"{number(max(f['max_position_error_m'] for f in frames))} m / "
         f"{number(max(f['max_velocity_error_mps'] for f in frames))} m/s"),
        ("Max attitude / output error",
         f"{number(max(f['max_orientation_error_rad'] for f in frames))} rad / "
         f"{number(max(t['max_output_error'] for t in traces))}"),
        ("Summaries identical / explained",
         f"{agreement.count('agree')} / {agreement.count('explained_by_scoring_rules')}"),
        ("Pre-start removal records excluded",
         str(sum(t['excluded_pre_start_records'] for t in traces))),
        *[(f"Scenarios with {label}", str(count)) for (label, _), count in zip(features, counts)],
    ]
    return "\n".join([
        "% Generated by paper/data/make_tables.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Differential testing over {len(results)} generated scenarios",
        "(\\texttt{generate\\_scenarios.py}, seed 1), with the same checks as",
        "Table~\\ref{tab:agreement}.}",
        "\\label{tab:generated}",
        "\\footnotesize",
        "\\begin{tabularx}{\\columnwidth}{P{0.42\\columnwidth}",
        "  >{\\raggedright\\arraybackslash}X}",
        "\\toprule",
        *[f"{name} & {value} \\\\" for name, value in rows],
        "\\bottomrule",
        "\\end{tabularx}",
        "\\end{table}",
        "",
    ])


def sensitivity_table():
    if not SENSITIVITY.is_file():
        return None
    report = json.loads(SENSITIVITY.read_text())
    rows = []
    for defect in report["defects"]:
        layers = sorted({layer for found in defect["missions"].values() for layer in found})
        rows.append(f"{latex_text(defect['name'])} & {len(defect['missions'])} & "
                    f"{', '.join(layers) if layers else '\\textbf{missed}'} \\\\")
    detected = sum(defect["detected"] for defect in report["defects"])
    return "\n".join([
        "% Generated by paper/data/make_tables.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Planted defects: {detected} of {len(report['defects'])} detected. Each",
        "is a one-line change applied to a copy of the Rust source and compared",
        "with the saved C++ runs of Table~\\ref{tab:agreement}. Missions counts the",
        "matrix missions that failed; the layers are those that reported it.}",
        "\\label{tab:sensitivity}",
        "\\footnotesize",
        "\\begin{tabularx}{\\columnwidth}{>{\\raggedright\\arraybackslash}Xrl}",
        "\\toprule",
        "Defect & Missions & Detected by \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabularx}",
        "\\end{table}",
        "",
    ])


def noise_table():
    if not NOISE.is_file():
        return None
    report = json.loads(NOISE.read_text())
    rows = []
    for name, quantity in report["quantities"].items():
        rows.append(" & ".join([
            name.replace("_", "\\_"),
            f"{quantity['cpp_mean']:.3f} / {quantity['rust_mean']:.3f}",
            f"{quantity['cpp_std']:.3f} / {quantity['rust_std']:.3f}",
            f"{quantity['ks_statistic']:.4f}", f"{quantity['p_value']:.3f}",
        ]) + " \\\\")
    samples = next(iter(report["quantities"].values()))["cpp_samples"]
    return "\n".join([
        "% Generated by paper/data/make_tables.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{NoisyContacts error distributions, C++ / Rust, from",
        f"{samples:,} samples per quantity and simulator. Two-sample Kolmogorov-Smirnov",
        f"test; the Bonferroni threshold is {report['per_test_threshold']:.4f}. Position",
        "and velocity errors in m and m/s; attitude as the error rotation angle.}",
        "\\label{tab:noise}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lllll}",
        "\\toprule",
        "Quantity & Mean & Std. dev. & $D$ & $p$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ])


def parity_table():
    """The one-table summary for the main text."""
    matrix, generated = cases(COMPARISON), cases(GENERATED)
    defects = json.loads(SENSITIVITY.read_text())["defects"]
    noise = json.loads(NOISE.read_text())["quantities"]
    long_runs = cases(LONG)
    divergence = json.loads((LONG / "divergence.json").read_text())["cases"] \
        if (LONG / "divergence.json").is_file() else []
    runs = matrix + generated + long_runs
    passing = [r for r in runs if r["passed"]]
    worst = max(r["comparison"]["max_position_error_m"] for r in passing)
    deliveries = sum(r["trace_comparison"]["deliveries"] for r in runs)
    differing = [r["trace_comparison"].get("delivery_mismatches") for r in runs]
    delivery_note = (f"{sum(differing):,} groups differ" if None not in differing
                     else "mismatch count not recorded in this data")
    rows = [
        ("Curated missions", f"{sum(r['passed'] for r in matrix)} of {len(matrix)} pass"),
        ("Generated scenarios", f"{sum(r['passed'] for r in generated)} of {len(generated)} pass"),
    ]
    if long_runs:
        diverged = [case for case in divergence if case["cpp_vs_rust_exceeds_tolerance_at_s"]]
        detail = ", ".join(f"{number(case['cpp_vs_rust_final_m'])} m" for case in diverged)
        rows.append(("Long runs, up to 1,000 s",
                     f"{sum(r['passed'] for r in long_runs)} of {len(long_runs)} pass"
                     + (f"; the other ends {detail} apart" if len(diverged) == 1
                        else f"; the others end {detail} apart" if diverged else "")))
    rows += [
        ("Planted bugs", f"{sum(d['detected'] for d in defects)} of {len(defects)} detected"),
        ("Sensor noise", f"no difference detected in {sum(q['passed'] for q in noise.values())} "
         f"of {len(noise)} marginal distributions"),
        ("Largest position difference, passing runs", f"{number(worst)} m"),
        ("Message deliveries compared", f"{deliveries:,}; {delivery_note}"),
    ]
    return "\n".join([
        "% Generated by paper/data/make_tables.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Parity evidence; the full results follow.}",
        "\\label{tab:parity}",
        "\\small",
        "\\begin{tabularx}{\\columnwidth}{P{0.34\\columnwidth}",
        "  >{\\raggedright\\arraybackslash}X}",
        "\\toprule",
        *[f"{name} & {value} \\\\" for name, value in rows],
        "\\bottomrule",
        "\\end{tabularx}",
        "\\end{table}",
        "",
    ])


def long_table():
    divergence = LONG / "divergence.json"
    if not divergence.is_file():
        return None
    def when(seconds):
        return "never" if seconds is None else f"{seconds:.1f} s"
    rows = []
    for case in json.loads(divergence.read_text())["cases"]:
        rows.append(" & ".join([
            verbatim_name(case["case"]), f"{case['end_s']:.0f} s",
            when(case["cpp_vs_rust_exceeds_tolerance_at_s"]),
            when(case["rust_vs_nudged_rust_exceeds_tolerance_at_s"]),
            number(case["cpp_vs_rust_final_m"]),
        ]) + " \\\\")
    return "\n".join([
        "% Generated by paper/data/make_tables.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Long runs. When C++ and Rust first differ by more than the $10^{-8}$~m",
        "tolerance, and, as a control, when Rust differs from itself after a",
        "one-unit-in-the-last-place change to initial roll, commanded speed, and turning",
        "radius, with each controller loop's proportional gain scaled by $1+10^{-12}$.",
        "Final: largest C++/Rust position difference at the end.}",
        "\\label{tab:long}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\begin{tabular}{lllll}",
        "\\toprule",
        "Scenario & Length & C++ vs Rust & Rust vs nudged & Final \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ])


def main():
    OUTPUT.mkdir(exist_ok=True)
    for name, table in (("long", long_table()), ("parity", parity_table()),
                        ("generated", generated_table()), ("sensitivity", sensitivity_table()),
                        ("noise", noise_table()), ("spatial", spatial_table()),
                        ("messages", messages_table()), ("stall", stall_table()),
                        ("checks", checks_table()), ("cpp_agreement", agreement_table())):
        if table is not None:
            write(name, table)


if __name__ == "__main__":
    main()
